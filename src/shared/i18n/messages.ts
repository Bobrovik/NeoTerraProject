export type MessageKey = keyof typeof en | CatalogMessageCode

export function translate(language: AppLanguage, key: MessageKey, values?: Record<string, string>): string {
  const copy = language === 'ru' ? ru : en
  const errors = language === 'ru' ? catalogErrors.ru : catalogErrors.en
  const template = key in copy ? copy[key as keyof typeof en] : errors[key as CatalogMessageCode]
  if (!values) {
    return template
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? '')
}
